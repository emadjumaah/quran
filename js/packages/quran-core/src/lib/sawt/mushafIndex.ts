/** بدايةُ كلّ سورةٍ في الترقيم العامّ — `SURAH_OFFSET[s-1]` قبلَ أوّل آية */
export const SURAH_OFFSET: number[] = [0];
for (let i = 0; i < AYAH_COUNTS.length; i++) SURAH_OFFSET.push(SURAH_OFFSET[i] + AYAH_COUNTS[i]);

/** «سورة:آية» ⇐ الرقم العامّ (١…٦٢٣٦) */
export const globalIdOf = (sura: number, ayah: number): number => SURAH_OFFSET[sura - 1] + ayah;

/** الرقم العامّ ⇐ [سورة، آية] */
export function locationOf(id: number): [number, number] {
  let s = 1;
  while (s < 114 && id > SURAH_OFFSET[s]) s++;
  return [s, id - SURAH_OFFSET[s - 1]];
}

export const pad3 = (n: number): string => String(n).padStart(3, "0");
