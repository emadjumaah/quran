/**
 * محلِّلُ العربيّة للبحث — قلبُ البحث في مشكاة (2026-07-21، أمر المالك: «البحث
 * أهمُّ ما في المشروع، نريده احترافيًّا ونهائيًّا»).
 *
 * الناسُ تبحث بالإملاء المعتاد لا برسم المصحف، وتُلصق حروفَ المعاني بأوّل الكلمة
 * («أكثرهم» · «فأكثرهم» · «وأكثرهم»)، وتخطئ في الهمزات («قارئ/قارء»، «سؤال/سوأل»)،
 * وتزيد الألفَ أو تنقصها («الرحمن/الرحمان»، «داود/داوود»). فالمحلّلُ يطوي ذلك كلَّه
 * على الطرفين معًا — السؤالِ والنصِّ — بخطواتٍ حتميّةٍ معلنة:
 *
 *   ١) تجريدُ التشكيل والتطويل والألف الخنجريّة.
 *   ٢) طيُّ صور الهمزة كلِّها إلى ا، و ى←ي، و ة←ه.
 *   ٣) نزعُ السوابق المتّصلة: و ف ب ك ل س + أل التعريف بتراكيبها (وال، فال، بال،
 *      كال، لل…) — بشرط بقاء جذعٍ ذي ثلاثة أحرفٍ فأكثر، كي لا تُمسخ الكلماتُ القصيرة.
 *   ٤) نزعُ اللواحق الضميريّة الشائعة (هم، هن، كم، كن، ها، هما، نا، ي، ك، ه)
 *      بشرط بقاء جذعٍ ثلاثيّ — «أكثرهم» و«أكثر» يلتقيان.
 *   ٥) ومفتاحُ هيكلٍ ثانٍ بلا ألفاتٍ ألبتّة، لمن زاد ألفًا أو نقصها.
 *
 * الطيُّ متماثلٌ على الطرفين، فلا يجلبُ أجنبيًّا عن السؤال؛ إنما يجمع صورَ الكلمة.
 */

// حركاتٌ وعلاماتُ ضبطٍ وتطويل — ليست حروفًا
const MARKS = /[ً-ٰٟۖ-ۭـ]/g;

/** التطبيعُ الأساسيّ: تجريدُ الضبط وطيُّ صور الحروف. */
export function normalizeAr(s: string): string {
  return (s || "")
    .replace(MARKS, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ؤ/g, "و")   // «سؤال» ← «سوال» كما يكتبها الناس
    .replace(/ئ/g, "ي")   // «قارئ» ← «قاري»
    .replace(/ء/g, "")    // الهمزةُ المفردة تُسقَط
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[^؀-ۿ\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** السوابقُ المتّصلة، الأطولُ أولًا (بعد التطبيع تصير الهمزةُ ألفًا).
 *  الشرطُ بقاءُ جذعٍ ثلاثيٍّ فأكثر — فيلتقي «وخلق» بـ«خلق» (رصدُ المالك
 *  2026-07-29: الباحثُ يتذكّر ﴿خلق منها زوجها﴾ ولا يتذكّر أن الواوَ من الكلمة).
 *  وحادثةُ «سوال»→«وال» القديمةُ (2026-07-21) سببُها سابقةُ «س» الاستقباليّة —
 *  وقد أُسقطت من القائمة نهائيًّا فلا تعود بهذا التخفيف. */
const PREFIXES: { p: string; min: number }[] = [
  { p: "وبال", min: 3 }, { p: "فبال", min: 3 }, { p: "وكال", min: 3 }, { p: "فكال", min: 3 },
  { p: "وال", min: 3 }, { p: "فال", min: 3 }, { p: "بال", min: 3 }, { p: "كال", min: 3 },
  { p: "لل", min: 3 }, { p: "ال", min: 3 },
  { p: "و", min: 3 }, { p: "ف", min: 3 }, { p: "ب", min: 3 }, { p: "ك", min: 3 }, { p: "ل", min: 3 },
];
/** اللواحقُ الضميريّةُ الشائعة، الأطولُ أولًا */
const SUFFIXES = ["هما", "كما", "هن", "هم", "كن", "كم", "نا", "ها", "ه", "ك", "ون", "ين", "ات", "ان"];
const MIN_STEM = 3;

/** جذعُ الكلمة بعد نزع السوابق واللواحق الشائعة (بحدٍّ أدنى لطول الجذع). */
export function stemAr(tok: string): string {
  let t = tok;
  for (const { p, min } of PREFIXES) {
    if (t.startsWith(p) && t.length - p.length >= min) { t = t.slice(p.length); break; }
  }
  for (const s of SUFFIXES) {
    if (t.endsWith(s) && t.length - s.length >= MIN_STEM) { t = t.slice(0, -s.length); break; }
  }
  return t;
}

/**
 * هيكلُ الكلمة الصامت: الجذعُ بلا حروفِ المدِّ والهمز (ا و ي) — به تلتقي صورُ
 * الكلمة مهما اختلف رسمُ همزها ومدِّها: «قارئ/قارء/قاري» و«سؤال/سوال/سءال»
 * و«الرحمن/الرحمان» و«داود/داوود». يُستعمل طبقةَ تقريبٍ لا طبقةَ دقّة، وبشرط
 * ألا يقلَّ الهيكلُ عن ثلاثة أحرف كي لا تتشابه الكلماتُ القصيرة.
 */
export const skeletonAr = (tok: string): string => stemAr(tok).replace(/[اوي]/g, "");

/**
 * صورُ كلمة الآية بعد نزع سابقةٍ متّصلةٍ محتملة — للمطابقة في الاتجاه الثاني:
 * الباحثُ يكتب «خلق» والآيةُ فيها «وخلق»، فتُقارَن كلمةُ السؤال بالكلمة وبصورها
 * المجرّدة معًا. مستوًى واحدٌ من النزع وبشرط بقاء ثلاثة أحرف — لا عودةَ لمسخ
 * الكلمات القصيرة.
 */
export function dePrefixAr(w: string): string[] {
  const out: string[] = [];
  for (const { p } of PREFIXES) {
    if (w.startsWith(p) && w.length - p.length >= MIN_STEM) out.push(w.slice(p.length));
  }
  return out;
}

/** كلماتُ نصٍّ مطبَّعةً (بلا تجذيع) */
export const tokensAr = (s: string): string[] => normalizeAr(s).split(" ").filter(Boolean);

/**
 * صورُ الكلمة الواحدة التي تُفهرَس/يُبحث بها: المطبَّعةُ نفسُها، وجذعُها،
 * وهيكلُها — فيلتقي الباحثُ بالنصّ من أيِّ صورةٍ كتبها.
 */
export function variantsAr(tok: string): string[] {
  const t = normalizeAr(tok);
  if (!t) return [];
  const st = stemAr(t);
  const sk = skeletonAr(t);
  const out = new Set([t]);
  if (st.length >= MIN_STEM) out.add(st);
  if (sk.length >= MIN_STEM) out.add(sk);
  return [...out];
}
