/**
 * **الجسرُ إلى «التلاوة»** — البابُ الخارجُ من مشكاة (خارطةُ المخرج §الجسر).
 *
 * «كلٌّ يحيل على الآخر عند حدِّه»: من كان في مشكاة على آيةٍ وأراد أن يتلوَها
 * ويُسمِّعها ذهب إلى التلاوة **عند تلك الآية بعينها**. ولا يُنقل غيرُ الموضع.
 *
 * ## الحارس — **ولا يُعرض زرٌّ ميّت**
 * نطاقُ التلاوة لا يقوم إلّا بنشرة المالك الأولى؛ فما لم يُرفع علمُ البيئة
 * `VITE_TILAWA_LIVE=1` في بناء مشكاة **لم يُعرض الزرُّ أصلًا** — فلا يلمس قارئٌ
 * بابًا يفضي إلى لا شيء. ورفعُه عند الإطلاق، وهو من خطوات المالك المكتوبة.
 *
 * **وهذا كلُّ ما زِيد في مشكاة في هذه الجلسة** (م٣ §٢: «التعديلُ الوحيدُ
 * المأذون») — هذا الملفُّ وزرٌّ واحدٌ في أدوات الآية القائمة، لا غير.
 */
export const TILAWA_BASE = "https://tilawa.mishkat.qa";

/** أقام نطاقُ التلاوة؟ — مطويٌّ بالافتراض، يُرفع بعلم بيئةٍ عند أوّل نشرة */
export const TILAWA_LIVE = import.meta.env.VITE_TILAWA_LIVE === "1";

/** رابطُ آيةٍ بعينها في التلاوة — `tilawa.mishkat.qa/#/{سورة}/{آية}` */
export const tilawaAyah = (surahNo: number, ayahNo: number): string =>
  `${TILAWA_BASE}/#/${surahNo}/${ayahNo}`;
