/** يُبرز ما بين نجمتين — فالبطاقةُ يجب أن يظهر فيها موضعُ الحسم لا أن يُقرأ سطرًا مستويًا */
function Emph({ text }: { text: string }) {
  return (
    <>
      {text.split(/\*\*/).map((part, i) => (i % 2 ? <b key={i}>{part}</b> : <span key={i}>{part}</span>))}
    </>
  );
}

