import { getAttribution } from "../audio";
import { MISHKAT_BASE, MISHKAT_LIVE } from "../bridge";
import Sheet from "./Sheet";

/**
 * **«عن التطبيق»** — ورقةٌ من الإعدادات (م٣ §١)، وفيها أربعةٌ لا خامسَ لها:
 * سطرُ تعريفٍ واحد · ومن أين النصّ · ومن أين التلاوةُ المسموعة · وبابُ مشكاة
 * لمن أراد التدبّرَ والبحث.
 *
 * **ولا لغةَ أدواتٍ ههنا ألبتّة**: لا اسمَ نموذجٍ ولا جلسةٍ ولا مكتبةٍ ولا
 * مسارٍ داخليّ — «من يفتحه لا يخطر بباله إلّا تطبيقُ جوال» (ميثاقُ الوجه).
 * **والإسنادُ يُقال ولا يُجمَّل**: منقولٌ يُسمّى ناقلُه.
 */
export default function About({ onClose }: { onClose: () => void }) {
  const recitation = getAttribution();
  /* **بابُ مشكاة في ذيلٍ ثابت** — كما في ورقة الانتقال سواءً بسواء */
  const bridge = MISHKAT_LIVE ? (
    <a className="tw-about-link" data-bridge="mishkat-home" href={MISHKAT_BASE} target="_blank" rel="noopener">
      <b>مشكاة — للتدبّر والبحث</b>
      <span>
        المرجعُ الحاسوبيُّ للمصحف: طبقاتُه المحسوبة، وميزانُ الأقوال، والبيان، وفروقُ التنزيل،
        وتاريخُ النصّ.
      </span>
    </a>
  ) : undefined;
  return (
    <Sheet title="عن التطبيق" onClose={onClose} footer={bridge}>
      <div data-tw="about">
        {/* **سطرُ التعريف** — جملةُ التطبيق الحاكمة بلسان قارئها */}
        <p className="tw-about-lead">
          <b>التلاوة</b> مصحفٌ تقرأ فيه وتستمع، وتُسمِّع عليه وردَك فيجري المؤشّرُ مع صوتك
          ويقف بك على مواضع الالتباس فتثبت.
        </p>

        <p className="tw-stamp">
          <b>النصّ</b> — رسمُ المصحف العثمانيُّ وحدودُ صفحاته وأجزائه من مشروع «تنزيل»،
          منقولًا كما هو لا يُمَسّ منه حرف.
        </p>
        {/* **ولا نقطةَ بعد اسمٍ لاتينيّ** في فقرةٍ عربيّة: النقطةُ محايدةُ
            الاتّجاه فتُرمى إلى يسار السطر وحدَها فتُقرأ كسرًا في الرسم — فتُترك،
            **والإسنادُ يُقتبس من مصدره حرفًا** فلا يُكتب اسمٌ مرّتين. */}
        {recitation && (
          <p className="tw-stamp">
            <b>التلاوةُ المسموعة</b> — منقولةٌ: {recitation}
          </p>
        )}
      </div>
    </Sheet>
  );
}
